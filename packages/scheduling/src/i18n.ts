export type MessageLocale = keyof typeof CATALOGS;
export const MESSAGE_LOCALES = Object.keys(CATALOGS) as MessageLocale[];

/** The catalog for a locale someone gave us, however it's written. Anything else gets English. */
export function messageLocale(locale: string | null | undefined): MessageLocale {
  if (!locale) return "en";
  let parsed: Intl.Locale;
  try {
    parsed = new Intl.Locale(locale);
  } catch {
    return "en";
  }
  const { language, region, script } = parsed;
  if (language === "zh") {
    if (script) return script === "Hant" ? "zh-TW" : "zh-CN";
    return ["TW", "HK", "MO"].includes(region ?? "") ? "zh-TW" : "zh-CN";
  }
  if (language === "pt") return region === "BR" ? "pt-BR" : "pt";
  return language in CATALOGS ? (language as MessageLocale) : "en";
}

export type Translate = (key: MessageKey, values?: Record<string, string>) => string;

/** One pass over the template, so a title that looks like `{sender}` stays as it was typed. */
export function translator(locale: string | null | undefined): Translate {
  const catalog: Catalog = CATALOGS[messageLocale(locale)];
  return (key, values = {}) =>
    catalog[key].replace(/\{(\w+)\}/g, (match, name: string) => values[name] ?? match);
}

/** What to format dates with: their own locale, unless the words around it will be in English. */
export function dateLocale(locale: string | null | undefined): string {
  if (!locale) return "en-US";
  if (messageLocale(locale) !== "en") return locale;
  try {
    return new Intl.Locale(locale).language === "en" ? locale : "en-US";
  } catch {
    return "en-US";
  }
}

/** The `lang` of a message's HTML. */
export const messageLanguage = (locale: string | null | undefined): string => messageLocale(locale);
